function toPoints(flat: number[]): Point[] {
  const out: Point[] = [];
  for (let i = 0; i < flat.length; i += 2) out.push({ x: flat[i] / 100, y: flat[i + 1] / 100 });
  return out;
}

export const CALENDAR: Track[] = LAYOUTS.map(([name, flat]) => buildTrack(name, toPoints(flat)));

// Random circuit for the next race, never the same one twice in a row.
export function pickTrack(rng: () => number = Math.random, excludeName?: string): Track {
  const pool = CALENDAR.filter((t) => t.name !== excludeName);
  return pool[Math.floor(rng() * pool.length) % pool.length];
}
